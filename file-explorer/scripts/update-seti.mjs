// Refreshes the vendored Seti file icons from VS Code's theme-seti extension
// (MIT, see THIRD_PARTY_NOTICES.md): lib/seti-font.ts holds the font as
// base64 and lib/seti-theme.json the icon map, trimmed to what lib/seti.ts
// reads. Run with `npm run update-seti`.
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const BASE =
  "https://raw.githubusercontent.com/microsoft/vscode/main/extensions/theme-seti/icons";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

async function fetchOk(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response;
}

const font = Buffer.from(
  await (await fetchOk(`${BASE}/seti.woff`)).arrayBuffer(),
);
const theme = await (await fetchOk(`${BASE}/vs-seti-icon-theme.json`)).json();

// "\\E001" → ""
function glyph(fontCharacter) {
  return String.fromCodePoint(parseInt(fontCharacter.replace(/^\\/, ""), 16));
}

const icons = {};
for (const [id, definition] of Object.entries(theme.iconDefinitions)) {
  if (typeof definition.fontCharacter !== "string") continue;
  icons[id] = [glyph(definition.fontCharacter), definition.fontColor ?? null];
}

const trimmed = {
  icons,
  file: theme.file,
  fileExtensions: theme.fileExtensions,
  fileNames: theme.fileNames,
  languageIds: theme.languageIds,
  light: {
    file: theme.light.file,
    fileExtensions: theme.light.fileExtensions,
    fileNames: theme.light.fileNames,
    languageIds: theme.light.languageIds,
  },
};

await writeFile(
  join(root, "lib/seti-theme.json"),
  JSON.stringify(trimmed) + "\n",
);
await writeFile(
  join(root, "lib/seti-font.ts"),
  [
    "// Generated by scripts/update-seti.mjs from VS Code's theme-seti",
    "// (Seti UI, MIT; see THIRD_PARTY_NOTICES.md). Do not edit.",
    `export const SETI_FONT_BASE64 =\n  "${font.toString("base64")}";`,
    "",
  ].join("\n"),
);
console.log(
  `seti: ${Object.keys(icons).length} icons, font ${font.length} bytes`,
);
